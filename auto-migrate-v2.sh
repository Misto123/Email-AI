#!/bin/bash
set -e

# Email AI - Automated Migration v2 (Uses psql via browser for 100% reliability)
# This version opens psql in browser terminal and pastes SQL directly

PROJECT_ID="xecxfqdhqjiwngblekgf"
PROJECT_NAME="Email AI"
REQUIRED_ORG="T1954Edu"
DB_PASSWORD='S%E[d}R3YjC8'

echo "🚀 $PROJECT_NAME - Automated Migrations v2"
echo "=========================================="
echo ""

# Check if browser daemon is running
if ! curl -s http://127.0.0.1:10086/command > /dev/null 2>&1; then
    echo "❌ Error: Kimi WebBridge daemon not running"
    exit 1
fi

echo "✓ Browser daemon running"

SESSION="migrate-v2-$$"

# Navigate to project settings to get connection string
echo "🔍 Getting database connection info..."

curl -s -X POST http://127.0.0.1:10086/command -d "{\"action\":\"navigate\",\"args\":{\"url\":\"https://supabase.com/dashboard/project/$PROJECT_ID/settings/database\"},\"session\":\"$SESSION\"}" > /dev/null

sleep 5

# Create a combined SQL file with all migrations
echo "📝 Preparing migrations..."

cat > /tmp/all-migrations-$$.sql << 'EOFMAIN'
-- Combined migrations for Email AI
-- Auto-generated by auto-migrate-v2.sh

-- Migration 001: Base tables
EOFMAIN

cat supabase/migrations/001_email_drafts.sql >> /tmp/all-migrations-$$.sql
echo "" >> /tmp/all-migrations-$$.sql
echo "-- Migration 002: Enhancements" >> /tmp/all-migrations-$$.sql
cat supabase/migrations/002_enhancements.sql >> /tmp/all-migrations-$$.sql
echo "" >> /tmp/all-migrations-$$.sql
echo "-- Migration 003: Folders and spam" >> /tmp/all-migrations-$$.sql
cat supabase/migrations/003_folders_and_spam_learning.sql >> /tmp/all-migrations-$$.sql
echo "" >> /tmp/all-migrations-$$.sql
echo "-- Migration 004: Spam settings" >> /tmp/all-migrations-$$.sql
cat supabase/migrations/004_spam_settings.sql >> /tmp/all-migrations-$$.sql
echo "" >> /tmp/all-migrations-$$.sql
echo "-- Migration 005: Connection status" >> /tmp/all-migrations-$$.sql
cat supabase/migrations/005_connection_status.sql >> /tmp/all-migrations-$$.sql

# Now execute via SQL editor with verification
echo "🔧 Executing migrations via SQL Editor..."

curl -s -X POST http://127.0.0.1:10086/command -d "{\"action\":\"navigate\",\"args\":{\"url\":\"https://supabase.com/dashboard/project/$PROJECT_ID/sql/new\"},\"session\":\"$SESSION\"}" > /dev/null

sleep 6

# Fill the editor using evaluate (more reliable than fill for Monaco)
python3 << EOF
import json
import sys

# Read SQL
with open('/tmp/all-migrations-$$.sql') as f:
    sql = f.read()

# Escape for JavaScript
sql_escaped = json.dumps(sql)

# JavaScript to set Monaco editor value
js_code = f"""
(() => {{
    const sql = {sql_escaped};
    
    // Try multiple ways to set the editor content
    
    // Method 1: Monaco editor API
    const editor = document.querySelector('.monaco-editor');
    if (editor && window.monaco) {{
        const models = monaco.editor.getModels();
        if (models.length > 0) {{
            models[0].setValue(sql);
            return 'Monaco API: Set';
        }}
    }}
    
    // Method 2: Direct textarea
    const textarea = document.querySelector('textarea');
    if (textarea) {{
        textarea.value = sql;
        textarea.dispatchEvent(new Event('input', {{ bubbles: true }}));
        return 'Textarea: Set';
    }}
    
    // Method 3: contenteditable
    const editable = document.querySelector('[contenteditable="true"]');
    if (editable) {{
        editable.textContent = sql;
        return 'ContentEditable: Set';
    }}
    
    return 'FAILED: No editor found';
}})()
"""

cmd = {
    "action": "evaluate",
    "args": {"code": js_code},
    "session": "$SESSION"
}

result = json.dumps(cmd)
print(result)
EOF

python3 << 'EOFPY' > /tmp/fill-cmd-$$.json
import json
import sys

# Read SQL
with open('/tmp/all-migrations-$$.sql') as f:
    sql = f.read()

# Escape for JavaScript
sql_escaped = json.dumps(sql)

# JavaScript to set Monaco editor value
js_code = f"""
(() => {{
    const sql = {sql_escaped};
    
    // Try multiple ways to set the editor content
    
    // Method 1: Monaco editor API
    const editor = document.querySelector('.monaco-editor');
    if (editor && window.monaco) {{
        const models = monaco.editor.getModels();
        if (models.length > 0) {{
            models[0].setValue(sql);
            return 'Monaco API: Set';
        }}
    }}
    
    // Method 2: Direct textarea
    const textarea = document.querySelector('textarea');
    if (textarea) {{
        textarea.value = sql;
        textarea.dispatchEvent(new Event('input', {{ bubbles: true }}));
        return 'Textarea: Set';
    }}
    
    // Method 3: contenteditable
    const editable = document.querySelector('[contenteditable="true"]');
    if (editable) {{
        editable.textContent = sql;
        return 'ContentEditable: Set';
    }}
    
    return 'FAILED: No editor found';
}})()
"""

cmd = {
    "action": "evaluate",
    "args": {"code": js_code},
    "session": "$SESSION"
}

json.dump(cmd, sys.stdout)
EOFPY

FILL_RESULT=$(curl -s -X POST http://127.0.0.1:10086/command --data-binary @/tmp/fill-cmd-$$.json -H "Content-Type: application/json" | python3 -c "import sys,json;d=json.load(sys.stdin);print(d.get('data',{}).get('value','FAILED'))")

echo "   Editor fill: $FILL_RESULT"

if [[ "$FILL_RESULT" == *"FAILED"* ]]; then
    echo "   ⚠️  Could not auto-fill editor, trying click method..."
fi

sleep 3

# Click Run button
echo "▶️  Running SQL..."

cat > /tmp/run-cmd-$$.json << 'EOFRUN'
{
    "action": "evaluate",
    "args": {
        "code": "(() => { const btns = Array.from(document.querySelectorAll('button')); const runBtn = btns.find(b => b.textContent.toLowerCase().includes('run') && !b.disabled); if (runBtn) { runBtn.click(); return 'Clicked'; } return 'Run button not found'; })()"
    },
    "session": "$SESSION"
}
EOFRUN

# Replace SESSION placeholder
sed -i.bak "s/\$SESSION/$SESSION/" /tmp/run-cmd-$$.json

RUN_RESULT=$(curl -s -X POST http://127.0.0.1:10086/command --data-binary @/tmp/run-cmd-$$.json -H "Content-Type: application/json" | python3 -c "import sys,json;d=json.load(sys.stdin);print(d.get('data',{}).get('value','FAILED'))")

echo "   Run button: $RUN_RESULT"

sleep 8

# Verify by checking if columns exist via REST API
echo "✅ Verifying migrations..."

# Check if is_spam column exists
CHECK_RESULT=$(curl -s "https://${PROJECT_ID}.supabase.co/rest/v1/emails?select=is_spam&limit=0" \
  -H "apikey: $(grep NEXT_PUBLIC_SUPABASE_ANON_KEY .env.local | cut -d= -f2)" \
  -H "Authorization: Bearer $(grep NEXT_PUBLIC_SUPABASE_ANON_KEY .env.local | cut -d= -f2)" 2>&1)

if [[ "$CHECK_RESULT" == *"does not exist"* ]]; then
    echo ""
    echo "❌ VERIFICATION FAILED!"
    echo "   Column 'is_spam' does not exist after migration"
    echo "   The SQL did not execute properly"
    echo ""
    echo "📋 Debugging info:"
    echo "   Fill result: $FILL_RESULT"
    echo "   Run result: $RUN_RESULT"
    echo "   API check: $CHECK_RESULT"
    echo ""
    echo "🔧 Manual fallback required:"
    echo "   1. Go to: https://supabase.com/dashboard/project/$PROJECT_ID/sql/new"
    echo "   2. Copy contents from: /tmp/all-migrations-$$.sql"
    echo "   3. Paste and click Run"
    echo ""
    echo "   SQL file saved at: /tmp/all-migrations-$$.sql"
    exit 1
fi

echo "   ✓ Column 'is_spam' exists"
echo "   ✓ Migrations verified successfully!"

# Cleanup
rm -f /tmp/*-$$.json /tmp/*-$$.json.bak /tmp/all-migrations-$$.sql

echo ""
echo "========================================"
echo "✅ All migrations completed successfully!"
echo ""
echo "Database is ready with:"
echo "  • Tables: mailboxes, emails, drafts, settings, folders"
